// Command labelgen generates the labels package from labels.yaml.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"

	"sigs.k8s.io/yaml"
)

type label struct {
	Name        string `json:"name"`
	Description string `json:"description"`
}

type vocabulary struct {
	Subject  []label `json:"subject"`
	Build    []label `json:"build"`
	Reserved []label `json:"reserved"`
}

func main() {
	in := flag.String("in", "", "path to labels.yaml")
	out := flag.String("out", "", "path to the generated Go file")
	pkg := flag.String("package", "", "package name of the generated file")
	flag.Parse()

	src, err := generate(*in, *pkg)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func generate(path, pkg string) ([]byte, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var v vocabulary
	if err := yaml.UnmarshalStrict(raw, &v); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if err := validate(v); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/labelgen from labels.yaml. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// Subject labels describe what a signal is about. Use them as metric label\n// names and as log keys.\n")
	fmt.Fprintf(&b, "const (\n")
	for _, l := range v.Subject {
		fmt.Fprintf(&b, "\t// %s is the %q label. %s\n", constName(l.Name), l.Name, l.Description)
		fmt.Fprintf(&b, "\t%s = %q\n", constName(l.Name), l.Name)
	}
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// Build labels describe the binary that emitted a signal. This library sets\n// them; application code never does.\n")
	fmt.Fprintf(&b, "const (\n")
	for _, l := range v.Build {
		fmt.Fprintf(&b, "\t// %s is the %q label. %s\n", constName(l.Name), l.Name, l.Description)
		fmt.Fprintf(&b, "\t%s = %q\n", constName(l.Name), l.Name)
	}
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// reserved labels are set by the collection pipeline on metrics and log\n// streams. Code must never set them.\n")
	fmt.Fprintf(&b, "var reserved = map[string]string{\n")
	for _, l := range v.Reserved {
		fmt.Fprintf(&b, "\t%q: %q,\n", l.Name, l.Description)
	}
	fmt.Fprintf(&b, "}\n")
	return format.Source(b.Bytes())
}

// packageIdentifiers are declared by hand in the labels package, so no
// generated constant may take them.
var packageIdentifiers = map[string]bool{"IsReserved": true, "Reserved": true}

func validate(v vocabulary) error {
	seen := map[string]bool{}
	consts := map[string]string{}
	for i, group := range [][]label{v.Subject, v.Build, v.Reserved} {
		for _, l := range group {
			if !snakeCase(l.Name) {
				return fmt.Errorf("label %q is not lower snake case", l.Name)
			}
			if i < 2 {
				c := constName(l.Name)
				if packageIdentifiers[c] {
					return fmt.Errorf("label %q generates %s, which the labels package already declares", l.Name, c)
				}
				if other, ok := consts[c]; ok {
					return fmt.Errorf("labels %q and %q both generate %s", other, l.Name, c)
				}
				consts[c] = l.Name
			}
			if l.Description == "" {
				return fmt.Errorf("label %q has no description", l.Name)
			}
			if seen[l.Name] {
				return fmt.Errorf("label %q is listed more than once", l.Name)
			}
			seen[l.Name] = true
		}
	}
	return nil
}

// snakeCase reports whether name is lower case letters and digits in words
// joined by single underscores, starting with a letter.
func snakeCase(name string) bool {
	if name == "" || name[0] < 'a' || name[0] > 'z' {
		return false
	}
	for _, word := range strings.Split(name, "_") {
		if word == "" {
			return false
		}
		for _, r := range word {
			if (r < 'a' || r > 'z') && (r < '0' || r > '9') {
				return false
			}
		}
	}
	return true
}

func constName(name string) string {
	var b strings.Builder
	for _, part := range strings.Split(name, "_") {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
